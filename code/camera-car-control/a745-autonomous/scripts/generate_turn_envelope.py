"""Conservative directional quarter-turn envelopes from the current CAD footprint."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARGIN = 40
ROTATION_STEP = 2
BIN_DEGREES = 5


def hull(points):
    points = sorted(set(points))
    def cross(o, a, b):
        return (a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0])
    lower, upper = [], []
    for p in points:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(points):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1]+upper[:-1]


def geometry_values(geometry):
    audit = geometry['cad_navigation_audit']
    return (audit['front_extent_mm'], audit['rear_extent_mm'], audit['half_width_mm'],
            *geometry['lidar_origin_in_axle_frame_mm'][:2])


def envelopes(geometry):
    front, rear, width, lx, ly = geometry_values(geometry)
    radius = math.hypot(max(front, rear)+MARGIN, width+MARGIN)
    # Every continuous orientation is within one degree of a sampled one.
    # This extra square inflation covers that maximum corner displacement.
    sampling_pad = math.ceil(2*radius*math.sin(math.radians(ROTATION_STEP/4)))
    pad = MARGIN+sampling_pad
    result = []
    for sign in (1, -1):
        points = []
        for degrees in range(0, 91, ROTATION_STEP):
            c, s = math.cos(math.radians(sign*degrees)), math.sin(math.radians(sign*degrees))
            for x in (-rear-pad, front+pad):
                for y in (-width-pad, width+pad):
                    points.append((x*c-y*s-lx, x*s+y*c-ly))
        polygon = hull(points)
        # A ray from the lidar intersects this convex, origin-containing hull.
        def ray_distance(degrees):
            dx, dy = math.cos(math.radians(degrees)), math.sin(math.radians(degrees))
            limit = float('inf')
            for i, p in enumerate(polygon):
                q = polygon[(i+1) % len(polygon)]
                nx, ny = q[1]-p[1], p[0]-q[0]
                bound = nx*p[0]+ny*p[1]
                assert bound > 0, 'Lidar must be inside the inflated starting footprint'
                divisor = nx*dx+ny*dy
                if divisor > 1e-9:
                    limit = min(limit, bound/divisor)
            return limit
        vertices = [math.degrees(math.atan2(y, x)) % 360 for x, y in polygon]
        limits = []
        for low in range(0, 360, BIN_DEGREES):
            high = low+BIN_DEGREES
            # A polygon's radial maximum within a bin is at a bin endpoint
            # or polygon vertex. Round outward, plus 2mm numeric allowance.
            candidates = [low, high]+[v for v in vertices if low <= v <= high]
            limits.append(math.ceil(max(map(ray_distance, candidates)))+2)
        assert max(limits) < 512
        result.append(limits)
    return result, sampling_pad


def render(geometry):
    (left, right), sampling_pad = envelopes(geometry)
    lines = ['`timescale 1ns/1ps', '`default_nettype none',
             '// Generated by scripts/generate_turn_envelope.py; do not edit the table.',
             f'// CAD (front,rear,half-width,lidar-X,Y): {geometry_values(geometry)} mm.',
             f'// 0..90 degree swept hull; margin {MARGIN}mm + angular sampling {sampling_pad}mm.',
             '// Per 5-degree bin, maximum radial extent including both endpoints.',
             'module a745_turn_envelope(input wire [6:0] bin,',
             ' output reg [8:0] left_limit,right_limit);',
             ' always @* begin', '  left_limit=511;right_limit=511;', '  case(bin)']
    for i, (l, r) in enumerate(zip(left, right)):
        lines.append(f"   7'd{i}:begin left_limit=9'd{l};right_limit=9'd{r};end")
    lines += ['   default:begin end', '  endcase', ' end', 'endmodule', '`default_nettype wire', '']
    return '\n'.join(lines)


def check_current(geometry):
    path = ROOT/'rtl/a745_turn_envelope.v'
    if not path.is_file() or path.read_text() != render(geometry):
        raise ValueError('Turn envelope does not match CAD; run scripts/generate_turn_envelope.py')


if __name__ == '__main__':
    ap = argparse.ArgumentParser();ap.add_argument('--check', action='store_true');args = ap.parse_args()
    geometry = json.loads((ROOT/'config/geometry.json').read_text())
    if args.check:
        check_current(geometry)
    else:
        (ROOT/'rtl/a745_turn_envelope.v').write_text(render(geometry), encoding='utf-8')
