const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const { chromium } = require('C:/Users/Shan_/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async () => {
  const out = path.join(__dirname, 'v1-fixed-front-wheels');
  const browser = await chromium.launch({headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page = await browser.newPage({viewport: {width: 1920, height: 1280}, deviceScaleFactor: 1});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(pathToFileURL(path.join(out, '查看模型.html')).href);
  await page.waitForFunction(() => window.chassisViewerState?.rendered === true);
  const initial = await page.evaluate(() => window.chassisViewerState);
  if (initial.parts !== 173) throw new Error('Unexpected mesh count');
  await page.screenshot({path: path.join(out, 'preview-viewer.png')});
  await page.locator('#view').screenshot({path:path.join(out,'preview-assembled.png')});
  await page.locator('#electronics').uncheck();
  const hidden = await page.evaluate(() => window.chassisViewerState);
  if (hidden.visible >= initial.visible) throw new Error('Hardware visibility did not change');
  await page.locator('#fasteners').uncheck();
  await page.locator('#view').screenshot({path:path.join(out,'preview-shell.png')});
  await page.locator('#electronics').check();
  await page.locator('#fasteners').check();
  await page.locator('#explode').evaluate(el => { el.value = '65'; el.dispatchEvent(new Event('input', {bubbles:true})); });
  const exploded = await page.evaluate(() => window.chassisViewerState);
  if (exploded.explode !== 65) throw new Error('Exploded view did not update');
  await page.locator('#view').screenshot({path:path.join(out,'preview-exploded.png')});
  await page.locator('#top').click();
  const top = await page.evaluate(() => window.chassisViewerState);
  if (top.view.phi > .01) throw new Error('Top view did not update');
  await page.locator('#explode').evaluate(el => {el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.locator('#view').screenshot({path:path.join(out,'preview-top.png')});
  await page.locator('#reset').click();
  await page.locator('#electronics').check();
  await page.locator('#explode').evaluate(el => { el.value = '0'; el.dispatchEvent(new Event('input', {bubbles:true})); });
  const linkNames = ['EdgeMind_Shell.step','EdgeMind_Assembly.step','EdgeMind_Chassis.FCStd','EdgeMind_Assembly.glb'];
  for (const file of linkNames) if (!fs.statSync(path.join(out,file)).size) throw new Error('Missing file: '+file);
  if (errors.length) throw new Error(JSON.stringify(errors));
  const report = {file_uri_works:true,initial,hardware_hidden:hidden,exploded,top,console_errors:errors,download_targets_exist:linkNames};
  fs.writeFileSync(path.join(out,'viewer-verification.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({rendered:true,parts:initial.parts,hardware_toggle:true,explode:true,top_view:true,console_errors:errors}));
  await browser.close();
})().catch(error => { console.error(error); process.exitCode=1; });
